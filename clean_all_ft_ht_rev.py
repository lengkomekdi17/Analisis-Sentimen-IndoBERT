tokenizer = BertTokenizer.from_pretrained("indobenchmark/indobert-base-p1")

class TextDataset(Dataset):
    def __init__(self, df, max_len=64):
        self.texts = df["Konten"].astype(str).tolist()
        self.labels = df["label_enc"].tolist()
        self.max_len = max_len

    def __len__(self):
        return len(self.texts)

    def __getitem__(self, idx):
        enc = tokenizer(self.texts[idx], truncation=True, padding="max_length",
                        max_length=self.max_len, return_tensors="pt")
        item = {k:v.squeeze() for k,v in enc.items()}
        item["labels"] = torch.tensor(self.labels[idx])
        return item

