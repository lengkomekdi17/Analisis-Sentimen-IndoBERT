device = "cuda" if torch.cuda.is_available() else "cpu"
scaler = GradScaler()

def objective(trial, df_train, method="ros", kfold=5):
    lr = trial.suggest_float("lr", 1e-5, 5e-5, log=True)
    batch_size = trial.suggest_categorical("batch_size", [8, 16])
    epochs = trial.suggest_int("epochs", 2, 3)

    X = df_train[["Konten"]]
    y = df_train["label_enc"]

    skf = StratifiedKFold(n_splits=kfold, shuffle=True, random_state=42)
    fold_scores = []

    for fold, (tr_idx, val_idx) in enumerate(skf.split(X, y), start=1):
        print(f"\n--- Fold {fold}/{kfold} ---")

        # Split data
        X_tr, X_val = X.iloc[tr_idx], X.iloc[val_idx]
        y_tr, y_val = y.iloc[tr_idx], y.iloc[val_idx]

        # Oversampling (TRAIN ONLY)
        df_tr = pd.DataFrame({
            "Konten": X_tr["Konten"],
            "label_enc": y_tr
        })
        df_tr = oversample_data(df_tr, method)

        # Dataloaders
        train_loader = DataLoader(
            TextDataset(df_tr),
            batch_size=batch_size,
            shuffle=True,
            num_workers=2,
            pin_memory=True,
            persistent_workers=True
        )

        val_loader = DataLoader(
            TextDataset(pd.DataFrame({
                "Konten": X_val["Konten"],
                "label_enc": y_val
            })),
            batch_size=16,
            num_workers=2,
            pin_memory=True,
            persistent_workers=True
        )

        # Model & optimizer
        model = BertForSequenceClassification.from_pretrained(
            "indobenchmark/indobert-base-p1",
            num_labels=3
        ).to(device)

        optimizer = AdamW(model.parameters(), lr=lr)

        # =====================
        # Training + HEARTBEAT
        # =====================
        for epoch in range(epochs):
            print(f"Epoch {epoch+1}/{epochs} (running)")  # heartbeat
            model.train()
            for batch in train_loader:
                batch = {k: v.to(device) for k, v in batch.items()}
                optimizer.zero_grad()
                with autocast():
                    loss = model(**batch).loss
                scaler.scale(loss).backward()
                scaler.step(optimizer)
                scaler.update()

        # ==========
        # Validation
        # ==========
        model.eval()
        preds, trues = [], []
        with torch.no_grad():
            for batch in val_loader:
                batch = {k: v.to(device) for k, v in batch.items()}
                out = model(**batch)
                preds.extend(out.logits.argmax(1).cpu().numpy())
                trues.extend(batch["labels"].cpu().numpy())

        f1 = f1_score(trues, preds, average="macro")
        print(f"Fold {fold} Macro F1: {f1:.4f}")
        fold_scores.append(f1)

        # =========================
        # CLEAN GPU & RAM PER FOLD
        # =========================
        del model, optimizer, train_loader, val_loader
        torch.cuda.empty_cache()
        gc.collect()
        time.sleep(2)

    return np.mean(fold_scores)

