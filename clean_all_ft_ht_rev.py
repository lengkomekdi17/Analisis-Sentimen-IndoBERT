def load_wordnet_indonesia(file_path):
    """
    Load WordNet Indonesia dari file tab (wn-ind-def.tab atau edaindo.tab) ke dictionary.
    Format file: synset_id <tab> POS <tab> LEMMA
    Dictionary output: {lemma: [sinonim1, sinonim2, ...]}
    """
    word2synonyms = {}
    synsets = {}

    with open(file_path, "r", encoding="utf-8") as f:
        for line in f:
            parts = line.strip().lower().split("\t")
            if len(parts) < 4:
                continue
            synset_id = parts[0]
            lemma = parts[3]

            # Simpan lemma per synset
            if synset_id not in synsets:
                synsets[synset_id] = []
            synsets[synset_id].append(lemma)

    # Buat dictionary kata → list sinonim
    for synset, lemmas in synsets.items():
        for lemma in lemmas:
            # sinonim = semua kata lain di synset
            syns = [l for l in lemmas if l != lemma]
            if syns:
                word2synonyms[lemma] = syns

    print(f"Loaded {len(word2synonyms)} words with synonyms from WordNet Indonesia")
    return word2synonyms

