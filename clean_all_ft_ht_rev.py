def random_oversample(df):
    max_n = df["label_enc"].value_counts().max()
    dfs=[]
    for lbl in df["label_enc"].unique():
        dfs.append(resample(df[df["label_enc"]==lbl], replace=True, n_samples=max_n, random_state=42))
    return pd.concat(dfs).reset_index(drop=True)

def synonym_replacement_wn(text, n=1):
    """Ganti kata dengan sinonim dari WordNet Indo jika ada."""
    if not isinstance(text, str):
        text = "" if pd.isna(text) else str(text)
    words = text.split()

    for _ in range(n):
        idxs = [i for i, w in enumerate(words) if w in wordnet_indo and wordnet_indo[w]]
        if not idxs:
            break
        idx = choice(idxs)
        words[idx] = choice(wordnet_indo[words[idx]])

    return " ".join(words)

def random_deletion(text, p=0.1):
    """
    Randomly delete words with probability p.
    Aman untuk NaN, float, dan string kosong.
    """
    if not isinstance(text, str):
        text = "" if pd.isna(text) else str(text)

    words = text.split()
    if len(words) == 0:
        return text

    new_words = [w for w in words if np.random.rand() > p]

    # kalau semua kata terhapus, kembalikan teks asli
    if len(new_words) == 0:
        return text

    return " ".join(new_words)

def eda_augment_wn_minority(df, num_aug=2):
    """
    EDA (Synonym Replacement + Random Deletion)
    HANYA untuk kelas minoritas
    """
    augmented_texts, augmented_labels = [], []

    # Hitung distribusi kelas
    label_counts = df["label_enc"].value_counts()
    majority_label = label_counts.idxmax()

    for label, count in label_counts.items():
        # ❗ Skip kelas mayoritas
        if label == majority_label:
            continue

        df_label = df[df["label_enc"] == label]

        for text in df_label["Konten"]:
            text = "" if pd.isna(text) else str(text)

            for _ in range(num_aug):
                t = synonym_replacement_wn(text, n=1)  # SR
                t = random_deletion(t, p=0.1)          # RD

                augmented_texts.append(t)
                augmented_labels.append(label)

    new_df = pd.DataFrame({
        "Konten": augmented_texts,
        "label_enc": augmented_labels
    })

    # Gabungkan data original + hasil EDA minoritas
    return pd.concat([df, new_df]).reset_index(drop=True)




def oversample_data(df, method="ros"):
    if method=="ros":
        return random_oversample(df)
    elif method=="eda":
        return eda_augment_wn_minority(df)
    elif method=="none":
        return df
    else:
        return df

