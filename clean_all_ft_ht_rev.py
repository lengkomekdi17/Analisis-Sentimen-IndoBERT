# Run Optuna & Train final
# ------------------------------
def run_method(df_train, df_test, method="ros", n_trials=3, kfold=5):
    print(f"\n=== RUNNING HYPERPARAM TUNING FOR {method.upper()} ===")

    # ===== OPTUNA CHECKPOINT (RUNTIME SAFE) =====
    storage_name = f"sqlite:///{method}_optuna_cleanall.db"
    study = optuna.create_study(
        direction="maximize",
        study_name=f"{method}_study",
        storage=storage_name,
        load_if_exists=True
    )

    study.optimize(
        lambda t: objective(t, df_train, method, kfold),
        n_trials=n_trials
    )

    print(f"\nBest params: {study.best_params}")
    print(f"Best CV mean F1: {study.best_value:.4f}")

    # Final train on full train set with best params
    params = study.best_params
    df_final = oversample_data(df_train, method)
    final_loader = DataLoader(
        TextDataset(df_final),
        batch_size=params["batch_size"],
        shuffle=True
    )

    final_model = BertForSequenceClassification.from_pretrained(
        "indobenchmark/indobert-base-p1",
        num_labels=3
    ).to(device)

    optimizer = AdamW(final_model.parameters(), lr=params["lr"])

    print(f"\n=== FINAL TRAINING ON FULL TRAIN SET ({method.upper()}) ===")
    for epoch in range(params["epochs"]):
        print(f"Epoch {epoch+1}/{params['epochs']}")
        final_model.train()
        for batch in tqdm(final_loader, desc="Training"):
            batch = {k:v.to(device) for k,v in batch.items()}
            optimizer.zero_grad()
            with autocast():
                loss = final_model(**batch).loss
            scaler.scale(loss).backward()
            scaler.step(optimizer)
            scaler.update()

    torch.save(final_model.state_dict(), f"{method}_final.pt")
    print(f"Model saved: {method}_final.pt")

    # Evaluate on test
    test_loader = DataLoader(TextDataset(df_test), batch_size=16)
    final_model.eval()
    preds, trues = [], []
    with torch.no_grad():
        for batch in test_loader:
            batch = {k:v.to(device) for k,v in batch.items()}
            out = final_model(**batch)
            preds.extend(out.logits.argmax(1).cpu().numpy())
            trues.extend(batch["labels"].cpu().numpy())

    print(f"\n=== TEST EVALUATION ({method.upper()}) ===")
    print(classification_report(trues, preds, target_names=["Negatif","Netral","Positif"]))

    cm = confusion_matrix(trues, preds, labels=[0,1,2])
    plt.figure(figsize=(6,5))
    sns.heatmap(
        cm, annot=True, fmt="d", cmap="Blues",
        xticklabels=["Negatif","Netral","Positif"],
        yticklabels=["Negatif","Netral","Positif"]
    )
    plt.xlabel("Predicted")
    plt.ylabel("Actual")
    plt.title(f"Confusion Matrix ({method.upper()})")
    plt.show()

    return study.best_value, f1_score(trues, preds, average="macro")

